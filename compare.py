# This program compares two numbers and prints the result.
# Its a conditional statement program
x = int(input("What's x? : "))
y = int(input("what's y?: "))

if x != y:
    print("x is not equal to y")
else:
    print("x is equal to y")

if x == y:
    print("x is equal to y")
else:
    print("x is not equal to y")